'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {execFileSync}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const digest=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
function findRoot(start=__dirname){for(let current=path.resolve(start);current!==path.dirname(current);current=path.dirname(current))if(fs.existsSync(path.join(current,'docs/math-port/scope.json'))&&fs.existsSync(path.join(current,'tools/mathjax-bundle/node_modules/@mathjax/src/package.json')))return current;return null;}
const rootArg=process.argv.indexOf('--repo-root');
assert.ok(rootArg<0?process.argv.length===2:(process.argv[rootArg+1]&&process.argv.length===rootArg+2),'usage: node common-table-source-witness.cjs [--repo-root <repository>]');
const root=rootArg<0?findRoot():path.resolve(process.argv[rootArg+1]);
assert.ok(root,'pass --repo-root <repository> or run from the repository');
const lock=JSON.parse(fs.readFileSync(path.join(root,'tests/math/fixtures/common-source/table-source-lock.json'),'utf8'));
const packageRoot=path.join(root,'tools/mathjax-bundle/node_modules/@mathjax');
assert.equal(JSON.parse(fs.readFileSync(path.join(packageRoot,'src/package.json'),'utf8')).version,lock.version,'MathJax package version');
assert.equal(JSON.parse(fs.readFileSync(path.join(packageRoot,'mathjax-newcm-font/package.json'),'utf8')).version,lock.version,'NewCM package version');
for(const [relative,expected] of Object.entries(lock.sourceTsSha256))assert.equal(digest(path.join(root,relative)),expected,`pinned Source changed: ${relative}`);
assert.equal(digest(path.join(root,'tools/math-port/table-layout-cases.json')),lock.corpusSha256,'pinned 14-case SVG corpus changed');
for(const [relative,expected] of Object.entries(lock.cjsSha256))assert.equal(digest(path.join(packageRoot,relative)),expected,`pinned MathJax/NewCM CJS changed: ${relative}`);
const observer=JSON.parse(execFileSync(process.execPath,[path.join(root,'tools/math-port/table-layout-source-observer.cjs')],{cwd:root,encoding:'utf8',maxBuffer:24*1024*1024}));
assert.equal(observer.version,lock.version);
assert.equal(observer.records.length,14,'table SVG corpus record count');
const dependencies=new Map(observer.dependencies.map(record=>[record.file,record.sha256]));
for(const [relative,expected] of Object.entries(lock.cjsSha256))assert.equal(dependencies.get(relative),expected,`observer did not load pinned ${relative}`);
const outputDir=path.join(root,'build/math-port/common-source');
fs.mkdirSync(outputDir,{recursive:true});
const svgEvidence=path.join(outputDir,'table-svg-source.json');
fs.writeFileSync(svgEvidence,JSON.stringify(observer,null,2)+'\n');
execFileSync(process.execPath,[path.join(__dirname,'common-table-branch-source-witness.cjs'),'--repo-root',root],{cwd:root,stdio:'inherit'});
process.stdout.write(`verified pinned table SVG corpus (${observer.records.length} cases) and exact Common wrapper branch cases; SVG evidence ${path.relative(root,svgEvidence)}\n`);
