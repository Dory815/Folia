// Root native Unicode tables derived from the pinned host, never used as a VM.
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),crypto=require('node:crypto');
assert.equal(process.version,'v24.13.0');assert.equal(process.versions.unicode,'16.0');assert.equal(process.versions.icu,'77.1');
const root=path.resolve(__dirname,'../..'),changes=[],ranges=[];let start=-1,last=0;
for(let cp=0;cp<=0x10FFFF;++cp){
    const original=String.fromCodePoint(cp),lower=original.toLowerCase(),out=Array.from(lower,c=>c.codePointAt(0));
    if(original!==lower){assert.ok(out.length<=3);changes.push({cp,out});}
    const flags=(/\p{Cased}/u.test(original)?1:0)|(/\p{Case_Ignorable}/u.test(original)?2:0);
    if(flags!==last){if(last)ranges.push({first:start,last:cp-1,flags:last});start=cp;last=flags;}
}
if(last)ranges.push({first:start,last:0x10FFFF,flags:last});
const fingerprint=crypto.createHash('sha256').update(JSON.stringify({changes,ranges})).digest('hex');
const output=`// Generated by case-host-data.cjs from Node 24.13.0 / Unicode 16.0 / ICU 77.1.
// Mapping/property payload SHA256: ${fingerprint}
module folia.math.util.js_case;
import std;
namespace folia::math::js_case::detail {
namespace {
struct Mapping{char32_t point;std::array<char32_t,3>lower;std::size_t count;};
constexpr Mapping mappings[]={
${changes.map(({cp,out})=>'{'+cp+',{'+out.concat(Array(3-out.length).fill(0)).join(',')+'},'+out.length+'},').join('\n')}
};
struct Range{char32_t first,last;unsigned flags;};
constexpr Range ranges[]={
${ranges.map(r=>'{'+r.first+','+r.last+','+r.flags+'},').join('\n')}
};
}
std::span<const char32_t> lowerMapping(char32_t point){
    std::size_t low=0,high=std::size(mappings);
    while(low<high){const auto mid=low+(high-low)/2;if(mappings[mid].point<point)low=mid+1;else high=mid;}
    if(low==std::size(mappings)||mappings[low].point!=point)return {};
    return {mappings[low].lower.data(),mappings[low].count};
}
unsigned caseProperties(char32_t point){
    std::size_t low=0,high=std::size(ranges);
    while(low<high){const auto mid=low+(high-low)/2;if(ranges[mid].last<point)low=mid+1;else high=mid;}
    return low<std::size(ranges)&&ranges[low].first<=point?ranges[low].flags:0;
}
}
`;
const file=path.join(root,'src/math/util/js_case_data.cpp');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(file,'utf8').replaceAll('\r\n','\n'),output);else fs.writeFileSync(file,output);
console.log(JSON.stringify({mappings:changes.length,property_ranges:ranges.length,payload_sha256:fingerprint,mode:process.argv.includes('--check')?'check':'generate'}));
